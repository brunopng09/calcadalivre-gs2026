-- =====================================================================
-- 14. CL_REFORMA — obra priorizada (mochila custo x beneficio)
-- =====================================================================
CREATE TABLE CL_REFORMA (
    id_reforma                    NUMBER         GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    id_trecho                     NUMBER,
    id_equipamento                NUMBER,
    nr_custo_estimado             NUMBER(10,2)   NOT NULL,
    nr_pessoas_beneficiadas_dia   NUMBER(6)      NOT NULL,
    nr_beneficio_score            NUMBER(10,2)   NOT NULL,
    ds_prioridade                 VARCHAR2(10)   NOT NULL,
    st_status                     VARCHAR2(20)   DEFAULT 'PLANEJADA' NOT NULL,
    dt_planejada                  DATE           NOT NULL,
    CONSTRAINT PK_CL_REFORMA              PRIMARY KEY (id_reforma),
    CONSTRAINT FK_CL_REFORMA_TRECHO       FOREIGN KEY (id_trecho)
        REFERENCES CL_TRECHO (id_trecho) ON DELETE SET NULL,
    CONSTRAINT FK_CL_REFORMA_EQUIPAMENTO  FOREIGN KEY (id_equipamento)
        REFERENCES CL_EQUIPAMENTO (id_equipamento) ON DELETE SET NULL,
    CONSTRAINT CK_CL_REFORMA_ALVO         CHECK (id_trecho IS NOT NULL OR id_equipamento IS NOT NULL),
    CONSTRAINT CK_CL_REFORMA_CUSTO        CHECK (nr_custo_estimado > 0),
    CONSTRAINT CK_CL_REFORMA_PESSOAS      CHECK (nr_pessoas_beneficiadas_dia > 0),
    CONSTRAINT CK_CL_REFORMA_BENEFICIO    CHECK (nr_beneficio_score >= 0),
    CONSTRAINT CK_CL_REFORMA_PRIORIDADE   CHECK (ds_prioridade IN ('ALTA','MEDIA','BAIXA')),
    CONSTRAINT CK_CL_REFORMA_STATUS       CHECK (st_status IN ('PLANEJADA','EM_EXECUCAO','CONCLUIDA'))
);

COMMENT ON TABLE  CL_REFORMA                           IS 'Obra priorizada pela mochila custo x beneficio (reforma de calcada ou equipamento).';
COMMENT ON COLUMN CL_REFORMA.id_reforma                IS 'Identificador da reforma (PK).';
COMMENT ON COLUMN CL_REFORMA.id_trecho                 IS 'Trecho a reformar (FK opcional -> CL_TRECHO).';
COMMENT ON COLUMN CL_REFORMA.id_equipamento            IS 'Equipamento a reformar (FK opcional -> CL_EQUIPAMENTO).';
COMMENT ON COLUMN CL_REFORMA.nr_custo_estimado         IS 'Custo estimado da reforma em reais.';
COMMENT ON COLUMN CL_REFORMA.nr_pessoas_beneficiadas_dia IS 'Estimativa de pessoas beneficiadas por dia.';
COMMENT ON COLUMN CL_REFORMA.nr_beneficio_score        IS 'Beneficio = pessoas por dia x gravidade media.';
COMMENT ON COLUMN CL_REFORMA.ds_prioridade             IS 'Prioridade da reforma (ALTA, MEDIA, BAIXA).';
COMMENT ON COLUMN CL_REFORMA.st_status                 IS 'Status da reforma (PLANEJADA, EM_EXECUCAO, CONCLUIDA).';
COMMENT ON COLUMN CL_REFORMA.dt_planejada              IS 'Data planejada da reforma.';
