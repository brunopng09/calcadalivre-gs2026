COMMENT ON COLUMN CL_CONSULTA_ROTA.dt_consulta       IS 'Data e hora da consulta.';
COMMENT ON COLUMN CL_CONSULTA_ROTA.nr_distancia_m    IS 'Distancia total da rota em metros.';
