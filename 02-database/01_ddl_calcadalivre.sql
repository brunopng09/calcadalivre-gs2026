-- 5. CL_TRECHO — trecho de calcada entre dois pontos (aresta do grafo)
-- =====================================================================
CREATE TABLE CL_TRECHO (
    id_trecho                NUMBER        GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    id_ponto_origem          NUMBER        NOT NULL,
    id_ponto_destino         NUMBER        NOT NULL,
    nm_rua                   VARCHAR2(120) NOT NULL,
    id_tipo_via              NUMBER        NOT NULL,
    nr_comprimento_m         NUMBER(6)     NOT NULL,
    nr_largura_total_m       NUMBER(4,2)   NOT NULL,
    nr_largura_livre_m       NUMBER(4,2)   NOT NULL,
    nr_inclinacao_pct        NUMBER(4,1)   NOT NULL,
    nr_buracos               NUMBER(1)     NOT NULL,
    st_tem_degrau            CHAR(1)       NOT NULL,
    nr_obstaculos_100m       NUMBER(3)     NOT NULL,
    st_ocupado_comercio      CHAR(1)       NOT NULL,
    st_rampa_esquina         CHAR(1)       NOT NULL,
    st_piso_tatil            CHAR(1)       NOT NULL,
    nr_idade_calcada_anos    NUMBER(3)     NOT NULL,
    nr_fluxo_pedestres_hora  NUMBER(6)     NOT NULL,
    nr_indice_acessibilidade NUMBER(5,1)   NOT NULL,
    nr_prob_intransitavel    NUMBER(5,4)   NOT NULL,
    dt_ultima_vistoria       DATE          NOT NULL,
    CONSTRAINT PK_CL_TRECHO                PRIMARY KEY (id_trecho),
    CONSTRAINT UK_CL_TRECHO_ORIGEM_DESTINO UNIQUE (id_ponto_origem, id_ponto_destino),
    CONSTRAINT FK_CL_TRECHO_PONTO_ORIGEM   FOREIGN KEY (id_ponto_origem)
        REFERENCES CL_PONTO (id_ponto),
    CONSTRAINT FK_CL_TRECHO_PONTO_DESTINO  FOREIGN KEY (id_ponto_destino)
        REFERENCES CL_PONTO (id_ponto),
    CONSTRAINT FK_CL_TRECHO_TIPO_VIA       FOREIGN KEY (id_tipo_via)
        REFERENCES CL_TIPO_VIA (id_tipo_via),
    CONSTRAINT CK_CL_TRECHO_ORIG_NE_DEST   CHECK (id_ponto_origem <> id_ponto_destino),
    CONSTRAINT CK_CL_TRECHO_COMPRIMENTO    CHECK (nr_comprimento_m > 0),
    CONSTRAINT CK_CL_TRECHO_LARG_TOTAL     CHECK (nr_largura_total_m BETWEEN 1.00 AND 6.00),
    CONSTRAINT CK_CL_TRECHO_LARG_LIVRE     CHECK (nr_largura_livre_m BETWEEN 0.00 AND 6.00),
    CONSTRAINT CK_CL_TRECHO_LIVRE_LE_TOT   CHECK (nr_largura_livre_m <= nr_largura_total_m),
    CONSTRAINT CK_CL_TRECHO_INCLINACAO     CHECK (nr_inclinacao_pct BETWEEN 0.0 AND 20.0),
    CONSTRAINT CK_CL_TRECHO_BURACOS        CHECK (nr_buracos BETWEEN 0 AND 3),
    CONSTRAINT CK_CL_TRECHO_DEGRAU         CHECK (st_tem_degrau IN ('S','N')),
    CONSTRAINT CK_CL_TRECHO_OBSTACULOS     CHECK (nr_obstaculos_100m >= 0),
    CONSTRAINT CK_CL_TRECHO_OCUPADO        CHECK (st_ocupado_comercio IN ('S','N')),
    CONSTRAINT CK_CL_TRECHO_RAMPA          CHECK (st_rampa_esquina IN ('S','N')),
    CONSTRAINT CK_CL_TRECHO_PISO_TATIL     CHECK (st_piso_tatil IN ('S','N')),
    CONSTRAINT CK_CL_TRECHO_IDADE          CHECK (nr_idade_calcada_anos BETWEEN 0 AND 80),
    CONSTRAINT CK_CL_TRECHO_FLUXO          CHECK (nr_fluxo_pedestres_hora >= 0),
    CONSTRAINT CK_CL_TRECHO_INDICE         CHECK (nr_indice_acessibilidade BETWEEN 0.0 AND 100.0),
    CONSTRAINT CK_CL_TRECHO_PROB           CHECK (nr_prob_intransitavel BETWEEN 0.0000 AND 1.0000)
);

COMMENT ON TABLE  CL_TRECHO                         IS 'Trecho de calcada entre dois pontos (aresta do grafo de navegacao).';
COMMENT ON COLUMN CL_TRECHO.id_trecho                IS 'Identificador do trecho (PK).';
COMMENT ON COLUMN CL_TRECHO.id_ponto_origem          IS 'Ponto de origem do trecho (FK -> CL_PONTO).';
COMMENT ON COLUMN CL_TRECHO.id_ponto_destino         IS 'Ponto de destino do trecho (FK -> CL_PONTO).';
COMMENT ON COLUMN CL_TRECHO.nm_rua                   IS 'Nome da rua do trecho.';
COMMENT ON COLUMN CL_TRECHO.id_tipo_via              IS 'Tipo de via do trecho (FK -> CL_TIPO_VIA).';
COMMENT ON COLUMN CL_TRECHO.nr_comprimento_m         IS 'Comprimento do trecho em metros.';
COMMENT ON COLUMN CL_TRECHO.nr_largura_total_m       IS 'Largura total da calcada em metros (1.00 a 6.00).';
COMMENT ON COLUMN CL_TRECHO.nr_largura_livre_m       IS 'Largura livre (sem obstaculos) em metros.';
COMMENT ON COLUMN CL_TRECHO.nr_inclinacao_pct        IS 'Inclinacao longitudinal em porcentagem (0 a 20).';
COMMENT ON COLUMN CL_TRECHO.nr_buracos               IS 'Quantidade de buracos (0 = piso bom, 3 = muito quebrado).';
COMMENT ON COLUMN CL_TRECHO.st_tem_degrau            IS 'Indica presenca de degrau ou escada (S/N).';
COMMENT ON COLUMN CL_TRECHO.nr_obstaculos_100m       IS 'Quantidade de obstaculos a cada 100 metros.';
COMMENT ON COLUMN CL_TRECHO.st_ocupado_comercio      IS 'Indica ocupacao do passeio pelo comercio (S/N).';
COMMENT ON COLUMN CL_TRECHO.st_rampa_esquina         IS 'Indica presenca de rampa na esquina (S/N).';
COMMENT ON COLUMN CL_TRECHO.st_piso_tatil            IS 'Indica presenca de piso tatil (S/N).';
COMMENT ON COLUMN CL_TRECHO.nr_idade_calcada_anos    IS 'Idade da calcada em anos (0 a 80).';
COMMENT ON COLUMN CL_TRECHO.nr_fluxo_pedestres_hora  IS 'Fluxo medio de pedestres por hora.';
COMMENT ON COLUMN CL_TRECHO.nr_indice_acessibilidade IS 'Indice de acessibilidade (0 a 100) previsto pelo modelo.';
COMMENT ON COLUMN CL_TRECHO.nr_prob_intransitavel    IS 'Probabilidade de o trecho ser intransitavel para cadeira de rodas (0 a 1).';
COMMENT ON COLUMN CL_TRECHO.dt_ultima_vistoria       IS 'Data da ultima vistoria de campo do trecho.';

