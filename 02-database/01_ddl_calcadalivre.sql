-- ---------------------------------------------------------------------
-- LIMPEZA (idempotencia): remove tabelas e sequences CL_* existentes.
-- Nunca toca em objetos de outras disciplinas (ALUNO, ALUNO1, etc.).
-- ---------------------------------------------------------------------
BEGIN
   FOR r IN (SELECT table_name
               FROM user_tables
              WHERE table_name LIKE 'CL\_%' ESCAPE '\')
   LOOP
      EXECUTE IMMEDIATE 'DROP TABLE "' || r.table_name || '" CASCADE CONSTRAINTS';
   END LOOP;

   FOR s IN (SELECT sequence_name
               FROM user_sequences
              WHERE sequence_name LIKE 'CL\_%' ESCAPE '\')
   LOOP
      EXECUTE IMMEDIATE 'DROP SEQUENCE "' || s.sequence_name || '"';
   END LOOP;
END;
